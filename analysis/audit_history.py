"""Extended-audit sheet history: label-only snapshots of every sheet version and an item-level changelog.

  python analysis/audit_history.py

Reads the label-only snapshots in docs/audit/extended/history/<version>/ and the current sheets in
docs/audit/extended/, scores each version against source gold (and between authors where both exist),
and writes docs/audit/extended/CHANGELOG.md listing every item whose label differs from the current sheet.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import yaml
from sklearn.metrics import cohen_kappa_score

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "docs" / "audit" / "extended"
HIST = EXT / "history"
PROCESSED = ROOT / "data" / "processed"
TASKS = {"t1_data2txt_shift": "t1_rag_hallucination", "t2_beavertails_pool": "t2_response_safety",
         "t3_heldout_groups": "t3_implicit_toxicity"}
VERSIONS = {
    "v1.1.0_scored": "Sheets scored for the 17 Nov 2026 draft and Zenodo v1.1.0 (incorrect copies).",
    "copy_2026-11-17_2325": "Intermediate incomplete copy (blank labels) present in the working tree before the correction.",
    "prefilled_template": "Second-author sheets as received, with pre-filled labels and blank rows.",
}


def annotators() -> list[str]:
    return yaml.safe_load((ROOT / "configs" / "tasks.yaml").read_text())["annotators"]


def load(path: Path) -> pd.Series:
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    return df.set_index("uid")["label"].str.strip()


def kappa(a: pd.Series, b: pd.Series) -> tuple[float, int]:
    m = a.isin(["0", "1"]) & b.isin(["0", "1"])
    return float(cohen_kappa_score(a[m].astype(int), b[m].astype(int))), int(m.sum())


def main() -> None:
    who_list = annotators()
    lines = ["# Extended audit: sheet versions and corrections", "",
             "Generated by `analysis/audit_history.py`. The current sheets (`../*_audit_<annotator>.csv`) are the "
             "authors' first-pass annotations and are the ones reported in the paper. Earlier versions are kept "
             "label-only under `history/` so every change is traceable.", ""]
    for v, desc in VERSIONS.items():
        lines.append(f"- `history/{v}/`: {desc}")
    lines += ["", "## Agreement by version", "",
              "| Audit | Version | Annotator | Labelled items | κ vs gold | κ between authors |", "|---|---|---|---|---|---|"]
    changes = []
    for name, task in TASKS.items():
        cur = {w: load(EXT / f"{name}_audit_{w}.csv") for w in who_list}
        uids = cur[who_list[0]].index
        gold = pd.read_parquet(PROCESSED / f"{task}.parquet", columns=["uid", "label"]).set_index("uid")["label"]
        gold = gold.loc[uids].astype(int).astype(str)
        for v in ["current", *VERSIONS]:
            sheets = cur if v == "current" else {
                w: load(HIST / v / f"{name}_audit_{w}.csv").loc[uids] for w in who_list
                if (HIST / v / f"{name}_audit_{w}.csv").exists()}
            if not sheets:
                continue
            btw = ""
            if len(sheets) == 2:
                k_b, n_b = kappa(*sheets.values())
                btw = f"{k_b:.3f} (n={n_b})"
            for w, lab in sheets.items():
                k, n = kappa(lab, gold)
                lines.append(f"| {name} | {v} | {w} | {n} | {k:.3f} | {btw} |")
                if v != "current":
                    diff = lab != cur[w]
                    if diff.any():
                        changes.append((name, v, w, diff, lab, cur[w], gold))
    lines += ["", "## Items that differ from the current sheets", ""]
    for name, v, w, diff, old, new, gold in changes:
        d = pd.DataFrame({"old": old[diff].replace("", "blank"), "current": new[diff], "gold": gold[diff]})
        lines.append(f"### {name}, {w}, `{v}` → current: {int(diff.sum())} items")
        lines.append("")
        lines.append("| uid | " + v + " | current | gold |")
        lines.append("|---|---|---|---|")
        lines += [f"| {u} | {r.old} | {r.current} | {r.gold} |" for u, r in d.iterrows()]
        lines.append("")
    (EXT / "CHANGELOG.md").write_text("\n".join(lines) + "\n")
    print(f"[write] {(EXT / 'CHANGELOG.md').relative_to(ROOT)} ({len(changes)} changed sheet versions)")


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
