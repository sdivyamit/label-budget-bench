def f3(v) -> str:
    return "--" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{float(v):.3f}"


def budget(v) -> str:
    if v is None:
        return "n.r."
    if isinstance(v, str):
        if v.strip().lower() in ("not reached", "n.r.", "nan", "none", "inf", ""):
            return "n.r."
        v = float(v)
    if not math.isfinite(float(v)):
        return "n.r."
    return f"{int(round(float(v))):,}".replace(",", "{,}")


def neg(x: float) -> str:
    return f"{0.0 if abs(x) < 0.0005 else x:+.3f}".replace("-", "$-$")


def write(name: str, lines: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text("% generated by analysis/paper_tables.py; do not edit\n" + "\n".join(lines) + "\n")
    print(f"tables/{name}.tex: {len(lines)} lines")


